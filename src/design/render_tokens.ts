/**
 * Renders the design tokens (src/design/tokens.ts) as CSS and as Figma
 * Variables in the W3C Design Tokens format (DTCG 2025.10).
 *
 * Pure functions, with the token tables passed in: this module has no
 * imports so `scripts/build-tokens.ts` can run it under Node's type
 * stripping, and the tests can compare its output with the committed files.
 */

/** Token tables, names without the leading `--`. */
export interface TokenSet {
  readonly shared: Readonly<Record<string, string>>;
  readonly dark: Readonly<Record<string, string>>;
  readonly light: Readonly<Record<string, string>>;
  /** Old name → new token name. */
  readonly aliases: Readonly<Record<string, string>>;
  /** Old name → its unchanged literal value. */
  readonly literals: Readonly<Record<string, string>>;
}

const CSS_HEADER = `/* Generated by scripts/build-tokens.ts from src/design/tokens.ts: do not edit.
   Change the tokens there, then run \`pnpm tokens\`. */`;

function declarations(tokens: Readonly<Record<string, string>>): string[] {
  return Object.entries(tokens).map(
    ([name, value]) => `  --${name}: ${value};`,
  );
}

/** The `tokens.css` stylesheet: dark on `:root`, light on `[data-theme]`. */
export function renderCss(set: TokenSet): string {
  const blocks = [
    CSS_HEADER,
    [
      ':root {',
      '  color-scheme: dark;',
      ...declarations(set.shared),
      ...declarations(set.dark),
      '}',
    ].join('\n'),
    [
      '[data-theme="light"] {',
      '  color-scheme: light;',
      ...declarations(set.light),
      '}',
    ].join('\n'),
    [
      '/* Pre-#184 names, removed once every consumer uses the tokens above.',
      '   Declared on the same element as their targets, so they follow the theme. */',
      ':root {',
      ...Object.entries(set.aliases).map(
        ([old, target]) => `  --${old}: var(--${target});`,
      ),
      ...declarations(set.literals),
      '}',
    ].join('\n'),
  ];
  return `${blocks.join('\n\n')}\n`;
}

// ── Figma Variables (DTCG) ───────────────────────────────────────────────────

type Json = string | number | boolean | null | Json[] | { [k: string]: Json };
type Group = { [k: string]: Json };

/** Namespaces, longest first so `font-weight-*` wins over `font-*`. */
const NAMESPACES = [
  'font-weight',
  'breakpoint',
  'duration',
  'leading',
  'spacing',
  'shadow',
  'radius',
  'color',
  'text',
  'font',
  'ease',
  'z',
] as const;

function split(name: string): [string, string] {
  for (const ns of NAMESPACES) {
    if (name === ns) return [ns, 'base'];
    if (name.startsWith(`${ns}-`)) return [ns, name.slice(ns.length + 1)];
  }
  throw new Error(`Token "${name}" has no known namespace`);
}

/** `#rrggbb` or `rgb(r g b / a)` as a DTCG sRGB color. */
function dtcgColor(value: string): Json {
  const hex = /^#([0-9a-f]{6})$/i.exec(value);
  if (hex?.[1]) {
    const n = hex[1];
    const c = [0, 2, 4].map((i) => parseInt(n.slice(i, i + 2), 16));
    return {
      colorSpace: 'srgb',
      components: c.map((v) => v / 255),
      hex: value,
    };
  }
  const rgb = /^rgb\((\d+) (\d+) (\d+)(?: \/ ([\d.]+))?\)$/.exec(value);
  if (rgb) {
    const c = [rgb[1], rgb[2], rgb[3]].map((v) => Number(v));
    const color: Group = {
      colorSpace: 'srgb',
      components: c.map((v) => v / 255),
      hex: `#${c.map((v) => v.toString(16).padStart(2, '0')).join('')}`,
    };
    if (rgb[4] !== undefined) color.alpha = Number(rgb[4]);
    return color;
  }
  throw new Error(`Unsupported color "${value}"`);
}

/**
 * `color-mix(in <space>, var(--token) P%, transparent)`, a token faded to
 * P%, as a DTCG color: the token's color with its alpha scaled by P. Mixing
 * with `transparent` interpolates premultiplied, so the hue stays the
 * token's in any color space. DTCG aliases cannot carry an alpha, hence the
 * resolved value; the description keeps the CSS source for the designer.
 */
const FADE =
  /^color-mix\(in [a-z]+, var\(--([a-z0-9-]+)\) ([\d.]+)%, transparent\)$/;

function fadedColor(
  value: string,
  lookup: Readonly<Record<string, string>>,
): Group | undefined {
  const m = FADE.exec(value);
  if (!m?.[1] || m[2] === undefined) return undefined;
  const source = lookup[m[1]];
  if (source === undefined) throw new Error(`Unknown token "${m[1]}"`);
  const color = dtcgColor(source) as Group;
  const alpha = typeof color.alpha === 'number' ? color.alpha : 1;
  // Rounded so float noise (0.08000000000000002) stays out of the file.
  color.alpha = Math.round(alpha * Number(m[2]) * 1e4) / 1e6;
  return { $type: 'color', $value: color, $description: value };
}

function dimension(value: string): Json {
  // `calc(infinity * 1px)` (a pill radius) has no DTCG form: Figma clamps.
  if (value.startsWith('calc(infinity')) return { value: 9999, unit: 'px' };
  const m = /^([\d.]+)(rem|px)$/.exec(value);
  if (!m) throw new Error(`Unsupported dimension "${value}"`);
  return { value: Number(m[1]), unit: m[2] as string };
}

/**
 * One DTCG token for a CSS value. `var(--x-y)` becomes a `{x.y}` alias;
 * `lookup` (every token of the theme) resolves the colors that a
 * `color-mix()` derives from another token.
 */
function dtcgToken(
  ns: string,
  value: string,
  lookup: Readonly<Record<string, string>>,
): Group {
  const ref = /^var\(--([a-z0-9-]+)\)$/.exec(value);
  if (ref?.[1]) {
    const [rns, rkey] = split(ref[1]);
    return { $value: `{${rns}.${rkey}}` };
  }
  switch (ns) {
    case 'color':
      return (
        fadedColor(value, lookup) ?? {
          $type: 'color',
          $value: dtcgColor(value),
        }
      );
    case 'spacing':
    case 'text':
    case 'radius':
    case 'breakpoint':
      return { $type: 'dimension', $value: dimension(value) };
    case 'duration':
      return {
        $type: 'duration',
        $value: { value: Number.parseFloat(value), unit: 'ms' },
      };
    case 'font-weight':
      return { $type: 'fontWeight', $value: Number(value) };
    case 'leading':
    case 'z':
      return { $type: 'number', $value: Number(value) };
    case 'font':
      return {
        $type: 'fontFamily',
        $value: value.split(',').map((f) => f.trim().replace(/^"|"$/g, '')),
      };
    case 'ease': {
      const nums = /cubic-bezier\(([^)]+)\)/.exec(value)?.[1];
      if (!nums) throw new Error(`Unsupported easing "${value}"`);
      return {
        $type: 'cubicBezier',
        $value: nums.split(',').map((n) => Number(n.trim())),
      };
    }
    case 'shadow':
      return { $type: 'shadow', $value: shadowLayers(value) };
    default:
      throw new Error(`No DTCG type for namespace "${ns}"`);
  }
}

/**
 * A CSS `box-shadow` (comma-separated layers of `[inset] x y [blur [spread]]
 * color`, colors as hex or space-separated `rgb()`) as DTCG shadow objects.
 */
function shadowLayers(value: string): Json[] {
  return value.split(/,(?![^(]*\))/).map((layer) => {
    // Lengths first, then the color (which may contain spaces inside rgb()).
    const parts = layer.trim().match(/rgb\([^)]*\)|\S+/g) ?? [];
    const inset = parts[0] === 'inset';
    const rest = inset ? parts.slice(1) : parts;
    const color = rest.pop();
    if (!color || rest.length < 2 || rest.length > 4) {
      throw new Error(`Unsupported shadow layer "${layer}"`);
    }
    const [x, y, blur = '0', spread = '0'] = rest;
    const px = (v: string | undefined): Json => ({
      value: Number.parseFloat(v ?? '0'),
      unit: 'px',
    });
    return {
      color: dtcgColor(color),
      offsetX: px(x),
      offsetY: px(y),
      blur: px(blur),
      spread: px(spread),
      inset,
    };
  });
}

function group(
  tokens: Readonly<Record<string, string>>,
  into: Group,
  lookup: Readonly<Record<string, string>>,
): void {
  for (const [name, value] of Object.entries(tokens)) {
    const [ns, key] = split(name);
    const g = (into[ns] ?? {}) as Group;
    g[key] = dtcgToken(ns, value, lookup) as Json;
    into[ns] = g;
  }
}

/**
 * The Figma Variables file of one theme (one Figma mode): shared tokens plus
 * that theme's colors and shadows, as pretty-printed JSON.
 */
export function renderFigma(set: TokenSet, theme: 'dark' | 'light'): string {
  const root: Group = {};
  const themed = theme === 'dark' ? set.dark : set.light;
  const lookup = { ...set.shared, ...themed };
  group(set.shared, root, lookup);
  group(themed, root, lookup);
  return `${JSON.stringify(root, null, 2)}\n`;
}
